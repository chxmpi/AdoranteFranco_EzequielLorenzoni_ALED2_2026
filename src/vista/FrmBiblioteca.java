    private void btnBuscarActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_btnBuscarActionPerformed
        // TODO add your handling code here:
         try {
 
            List<Libro> resultado;
            
            //el 0 es titulo y el 1 por autor en el combo box.
            if (cmdBuscarPor.getSelectedIndex() == 0) {
                resultado = controlador.buscarPorTitulo(
                        txtBuscarLibro.getText()
                );
            } else {
                resultado = controlador.buscarPorAutor(
                        txtBuscarLibro.getText()
                );
            }
 
            mostrarLibros(resultado);
 
            if (resultado.isEmpty()) {
                JOptionPane.showMessageDialog(
                        this,
                        "No se encontraron libros."
                );
            }
 
        } catch (IllegalArgumentException e) {
 
            JOptionPane.showMessageDialog(
                    this,
                    e.getMessage()
            );
 
        } catch (SQLException e) {
 
            JOptionPane.showMessageDialog(
                    this,
                    "Error al buscar: "
                    + e.getMessage()
            );
        }
 
    }//GEN-LAST:event_btnBuscarActionPerformed


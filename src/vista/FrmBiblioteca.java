        // Muestro en la tabla la lista de libros que me pasan
    private void mostrarLibros(List<Libro> lista) {
        DefaultTableModel modelo = (DefaultTableModel) tblLibros.getModel();
        modelo.setRowCount(0);
 
        for (Libro l : lista) {
            modelo.addRow(new Object[]{
                l.getId(),
                l.getTitulo(),
                l.getAutor(),
                l.getCategoria(),
                l.getEditorial(),
                l.getStock()
            });
        }
    }
 
    // Cargo en la tabla todos los libros de la base
    private void cargarTabla() {
        try {
            mostrarLibros(controlador.listar());
        } catch (SQLException e) {
            JOptionPane.showMessageDialog(
                    this,
                    "Error al cargar los libros: "
                    + e.getMessage()
            );
        }
    }
 
    // Limpio los campos y saco la seleccion de la tabla
    private void limpiarCampos() {
        txtTitulo.setText("");
        txtAutor.setText("");
        txtCategoria.setText("");
        txtEditorial.setText("");
        txtStock.setText("");
        tblLibros.clearSelection(); //si hay una fila ressaltada la deja sin resaltar
        txtTitulo.requestFocus();
    }
    private int obtenerIdSeleccionado() {
        int fila = tblLibros.getSelectedRow();
 
        if (fila == -1) {
            return 0;
        }
 
        return Integer.parseInt(tblLibros.getValueAt(fila, 0).toString());
    }
